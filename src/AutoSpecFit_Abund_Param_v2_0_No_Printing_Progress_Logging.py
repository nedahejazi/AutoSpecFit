def convert_asf_offsets_to_xh(
    asf_abundances: np.ndarray,
    stellar_parameters: StellarParameters,
    species: SpeciesConfig,
    config: AutoSpecFitConfig,
) -> np.ndarray:
    """Convert ASF abundance offsets to the physical [X/H] abundance scale.

    ASF fits an elemental abundance offset relative to the abundance pattern of
    the model atmosphere.  In Version 2 the atmosphere is itself fitted, so the
    conversion must use the FINAL adopted atmospheric composition:

        non-alpha elements: [X/H] = ASF(X) + [M/H]_final
        alpha elements:     [X/H] = ASF(X) + [M/H]_final
                                      + [alpha/Fe]_final

    ``config.alpha_species`` is defined in terms of spectral species and may
    contain ``OH``; for the elemental output table OH therefore maps to O.
    """
    asf = np.asarray(asf_abundances, dtype=float)
    metallicity = float(stellar_parameters.metallicity)
    alpha = float(stellar_parameters.alpha)

    alpha_elements = {
        "O" if name.upper() == "OH" else name
        for name in config.alpha_species
    }

    xh = asf + metallicity
    for species_index, element_name in enumerate(species.element_names):
        if element_name in alpha_elements and np.isfinite(xh[species_index]):
            xh[species_index] += alpha

    return xh


def write_final_abundance_table(
    final_not_rounded: np.ndarray,
    final_rounded: np.ndarray,
    final_errors: np.ndarray,
    final_stellar_parameters: StellarParameters,
    species: SpeciesConfig,
    config: AutoSpecFitConfig,
    nan_replacement_notes: Optional[List[str]] = None,
    per_parameter_systematics: Optional[Dict[str, np.ndarray]] = None,
    systematic_errors: Optional[np.ndarray] = None,
    total_errors: Optional[np.ndarray] = None,
) -> None:
    """Save final [X/H] abundances with random, systematic, and total errors.

    ``final_not_rounded`` and ``final_rounded`` are the native ASF abundance
    offsets from the dedicated final abundance fit.  The science abundance
    reported here is converted to [X/H] with the final fitted [M/H] and, for
    alpha elements, the final fitted [alpha/Fe].  The native ASF offset is kept
    as a separate column for traceability.

    The random abundance error is unchanged by adding fixed nominal atmospheric
    composition terms.  The systematic error supplied to this function is
    already evaluated on the [X/H] scale by
    ``run_systematic_abundance_error_analysis``.
    """
    output_path = Path(config.output_dir) / config.final_abundance_file

    random_errors = np.asarray(final_errors, dtype=float)
    if systematic_errors is None:
        systematic_errors = np.full_like(random_errors, np.nan)
    if total_errors is None:
        total_errors = random_errors.copy()

    if per_parameter_systematics is None:
        per_parameter_systematics = {}
    systematic_vmic = np.asarray(
        per_parameter_systematics.get("vmic", np.full_like(random_errors, np.nan)),
        dtype=float,
    )
    systematic_metallicity = np.asarray(
        per_parameter_systematics.get(
            "metallicity", np.full_like(random_errors, np.nan)
        ),
        dtype=float,
    )
    systematic_logg = np.asarray(
        per_parameter_systematics.get("logg", np.full_like(random_errors, np.nan)),
        dtype=float,
    )
    systematic_teff = np.asarray(
        per_parameter_systematics.get("teff", np.full_like(random_errors, np.nan)),
        dtype=float,
    )
    systematic_alpha = np.asarray(
        per_parameter_systematics.get("alpha", np.full_like(random_errors, np.nan)),
        dtype=float,
    )

    final_xh_not_rounded = convert_asf_offsets_to_xh(
        final_not_rounded, final_stellar_parameters, species, config
    )
    final_xh_rounded = np.round(final_xh_not_rounded, 3)

    table = pd.DataFrame(
        {
            "Element": species.element_names,
            "ASF_Offset": final_rounded,
            "Final_X_H": final_xh_rounded,
            "Final_Random_Error": random_errors,
            "Systematic_vmic": systematic_vmic,
            "Systematic_M_H": systematic_metallicity,
            "Systematic_logg": systematic_logg,
            "Systematic_Teff": systematic_teff,
            "Systematic_alpha": systematic_alpha,
            "Final_Systematic_Error": systematic_errors,
            "Final_Total_Error": total_errors,
        }
    )
    with open(output_path, "w") as handle:
        handle.write(
            "# Final elemental abundances on the [X/H] scale and 1-sigma uncertainties (dex)\n"
            f"# Final atmosphere: [M/H]={float(final_stellar_parameters.metallicity):+.2f}, "
            f"[alpha/Fe]={float(final_stellar_parameters.alpha):+.2f}\n"
            "# Non-alpha: [X/H] = ASF_Offset + [M/H]_final\n"
            "# Alpha:     [X/H] = ASF_Offset + [M/H]_final + [alpha/Fe]_final\n"
            "# Random error is unchanged by the abundance-scale conversion.\n"
            "# Per-parameter systematic columns are the mean absolute, linearly scaled +/-1-sigma [X/H] shifts.\n"
            "# Final_Systematic_Error is the quadrature sum of the five per-parameter systematic columns.\n"
            "# Total error = sqrt(Random_Error^2 + Systematic_Error^2)\n"
        )
        table.to_csv(handle, sep=" ", index=False, header=True, float_format="%.6f", na_rep="nan")

    if nan_replacement_notes:
        with open(output_path, "a") as handle:
            handle.write("\n# NaN abundance replacements used during follow-up model generation\n")
            for note in nan_replacement_notes:
                handle.write(f"# {note}\n")

    LOGGER.info("Wrote final abundance table: %s", output_path)


def species_abundance_errors_from_iteration(
    species_results: List[SpeciesIterationResult],
) -> np.ndarray:
    """Return one random abundance uncertainty per species.

    Each individual line receives a formal 1-sigma uncertainty from the local
    chi-square parabola using ``chi2 = chi2_min + 1``.  For a species with two
    or more accepted lines, the random abundance uncertainty combines:

        (1) the line-to-line sample standard deviation of the accepted
            grid-based line abundances; and
        (2) the RMS of the finite individual-line chi-square uncertainties
            associated with accepted abundance solutions.

    These terms are added in quadrature.  For a species represented by only
    one accepted line, the random uncertainty is the formal chi-square error
    of that line.  If no finite formal error is available for a one-line
    species, the returned uncertainty is NaN rather than inventing an error.
    """
    species_errors: List[float] = []

    for result in species_results:
        accepted = np.asarray(result.clipped_line_abundances, dtype=float)
        accepted = accepted[np.isfinite(accepted)]

        if len(accepted) == 0:
            species_errors.append(np.nan)
            continue

        # Match accepted abundance values back to individual line results.
        # A used-index mask preserves multiplicity when two lines have the same
        # sampled best abundance.
        line_values = np.asarray(
            [line.best_abundance_grid for line in result.line_results], dtype=float
        )
        line_errors = np.asarray(
            [line.abundance_error for line in result.line_results], dtype=float
        )
        used = np.zeros(len(line_values), dtype=bool)
        accepted_errors: List[float] = []

        for abundance in accepted:
            candidates = np.where(
                (~used)
                & np.isfinite(line_values)
                & np.isclose(line_values, abundance, atol=1.0e-10, rtol=0.0)
            )[0]
            if len(candidates) == 0:
                continue
            idx = int(candidates[0])
            used[idx] = True
            if np.isfinite(line_errors[idx]) and line_errors[idx] > 0:
                accepted_errors.append(float(line_errors[idx]))

        finite_errors = np.asarray(accepted_errors, dtype=float)

        # One accepted line: only the formal chi-square error is defined.
        if len(accepted) == 1:
            species_errors.append(
                float(finite_errors[0]) if len(finite_errors) == 1 else np.nan
            )
            continue

        line_scatter = float(np.std(accepted, ddof=1))
        chi2_rms = (
            float(np.sqrt(np.mean(finite_errors**2)))
            if len(finite_errors) > 0
            else np.nan
        )

        if np.isfinite(line_scatter) and np.isfinite(chi2_rms):
            random_error = float(np.sqrt(line_scatter**2 + chi2_rms**2))
        elif np.isfinite(line_scatter):
            random_error = line_scatter
        elif np.isfinite(chi2_rms):
            random_error = chi2_rms
        else:
            random_error = np.nan

        species_errors.append(random_error)

    return np.asarray(species_errors, dtype=float)



