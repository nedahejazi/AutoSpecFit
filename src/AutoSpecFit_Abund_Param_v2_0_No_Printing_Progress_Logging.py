def run_autospecfit_abundance_pipeline(
    config: AutoSpecFitConfig,
    stellar_parameters: StellarParameters,
    species: SpeciesConfig,
    parameter_refiner: Optional[ParameterRefiner] = None,
) -> None:
    """Run ASF with automatic iteration/sub-step checkpoint and restart support."""

    config.output_dir.mkdir(parents=True, exist_ok=True)

    if config.refine_parameters_after_each_iteration and parameter_refiner is None:
        raise ValueError(
            "refine_parameters_after_each_iteration=True requires a parameter_refiner callback."
        )

    abundance_grid = np.asarray(config.abundance_values, dtype=float)
    lam_star, flux_star, err_flux_star = read_observed_spectrum(
        config.observed_spectrum_file,
        config.observed_wavelength_scale,
    )
    line_lists = read_all_line_lists(config, species)

    n_total_iterations = 1 + config.n_followup_iterations
    mean_history = np.full((species.n_species, n_total_iterations), np.nan)
    rounded_history = np.full((species.n_species, n_total_iterations), np.nan)

    current_stellar_parameters = round_all_stellar_parameters_to_grids(
        config,
        stellar_parameters,
    )
    stellar_parameters = current_stellar_parameters

    LOGGER.info(
        "Initial parameters rounded to adopted grids: "
        "Teff=%s logg=%s [M/H]=%s [alpha/Fe]=%s vmic=%s",
        current_stellar_parameters.teff,
        current_stellar_parameters.logg,
        current_stellar_parameters.metallicity,
        current_stellar_parameters.alpha,
        current_stellar_parameters.vmic,
    )

    last_parameter_errors: Dict[str, float] = {
        "teff": np.nan,
        "logg": np.nan,
        "metallicity": np.nan,
        "alpha": np.nan,
        "vmic": np.nan,
    }
    last_real_parameter_values: Dict[str, float] = {
        "teff": float(stellar_parameters.teff),
        "logg": float(stellar_parameters.logg),
        "metallicity": float(stellar_parameters.metallicity),
        "alpha": float(stellar_parameters.alpha),
        "vmic": float(stellar_parameters.vmic),
    }
    last_parameter_consistency_shifts: Dict[str, float] = {
        "teff": np.nan,
        "logg": np.nan,
        "metallicity": np.nan,
        "alpha": np.nan,
        "vmic": np.nan,
    }
    current_abundance_errors = np.full(species.n_species, np.nan)
    nan_replacement_notes: List[str] = []
    parameter_converged_for_next_iteration = True

    initialize_fresh_start_once(config)

    checkpoint = load_restart_checkpoint(
        config=config,
        species=species,
        n_total_iterations=n_total_iterations,
    )

    if checkpoint is None:
        next_stage = "abundance"
        iteration_id = 1
        # A genuinely new run starts clean cumulative/legacy history and progress files.
        parameter_history_path = Path(config.output_dir) / config.parameter_history_file
        abundance_history_path = Path(config.output_dir) / config.abundance_history_file
        legacy_parameter_history_path = Path(config.output_dir) / config.legacy_parameter_history_file
        for history_path in (parameter_history_path, abundance_history_path, legacy_parameter_history_path):
            if history_path.exists():
                history_path.unlink()
        clear_parameter_progress(config)
        log_mode = "w"
    else:
        next_stage = str(checkpoint["next_stage"])
        iteration_id = int(checkpoint["iteration_id"])
        current_stellar_parameters = round_all_stellar_parameters_to_grids(
            config,
            stellar_parameters_from_dict(
                checkpoint["current_stellar_parameters"]
            ),
        )
        mean_history = checkpoint["mean_history_array"]
        rounded_history = checkpoint["rounded_history_array"]
        last_parameter_errors.update(checkpoint["parameter_errors_dict"])
        last_real_parameter_values.update(checkpoint["real_parameter_values_dict"])
        last_parameter_consistency_shifts.update(
            checkpoint.get("parameter_consistency_shifts_dict", {})
        )
        if len(checkpoint["abundance_errors_array"]) == species.n_species:
            current_abundance_errors = checkpoint["abundance_errors_array"]
        parameter_converged_for_next_iteration = bool(
            checkpoint.get("parameter_converged_for_next_iteration", True)
        )
        nan_replacement_notes = list(checkpoint.get("nan_replacement_notes", []))
        log_mode = "a"

        if next_stage == "finished":
            LOGGER.info("Checkpoint indicates that ASF already finished successfully.")
            return

    parameter_history_path = Path(config.output_dir) / config.parameter_history_file
    abundance_history_path = Path(config.output_dir) / config.abundance_history_file
    legacy_parameter_history_path = Path(config.output_dir) / config.legacy_parameter_history_file

    if checkpoint is None:
        # Parameter iteration 1 is the original adopted atmosphere. Abundance
        # iteration 1 is evaluated with exactly this parameter set. Every later
        # parameter iteration N is obtained after abundance iteration N-1 and
        # is then used by abundance iteration N.
        initial_real_values = {
            "teff": float(current_stellar_parameters.teff),
            "logg": float(current_stellar_parameters.logg),
            "metallicity": float(current_stellar_parameters.metallicity),
            "alpha": float(current_stellar_parameters.alpha),
            "vmic": float(current_stellar_parameters.vmic),
        }
        initial_errors = {
            "teff": np.nan,
            "logg": np.nan,
            "metallicity": np.nan,
            "alpha": np.nan,
            "vmic": np.nan,
        }
        initial_consistency_shifts = {
            "teff": np.nan,
            "logg": np.nan,
            "metallicity": np.nan,
            "alpha": np.nan,
            "vmic": np.nan,
        }
        update_parameter_history_table(
            path=parameter_history_path,
            iteration_id=1,
            stellar_parameters=current_stellar_parameters,
            real_parameter_values=initial_real_values,
            parameter_errors=initial_errors,
            parameter_consistency_shifts=initial_consistency_shifts,
        )

    if checkpoint is not None:
        rebuild_history_outputs_from_restart(
            config=config,
            species=species,
            mean_history=mean_history,
            rounded_history=rounded_history,
            iteration_id=iteration_id,
            next_stage=next_stage,
            current_abundance_errors=current_abundance_errors,
            current_stellar_parameters=current_stellar_parameters,
            last_real_parameter_values=last_real_parameter_values,
            last_parameter_errors=last_parameter_errors,
            last_parameter_consistency_shifts=last_parameter_consistency_shifts,
        )

    log_path = Path(config.output_dir) / config.iteration_log_file

    with open(log_path, log_mode, buffering=1) as log_handle:
        if log_mode == "w":
            log_handle.write(
                "LineCenter BestFit_Abundance_PolyFit BestFit_Abundance_Original\n"
            )
            log_handle.write(
                "==================================================================\n"
            )
        else:
            log_handle.write(
                f"\n# ===== ASF RESTART: stage={next_stage}, iteration={iteration_id} =====\n"
            )
            log_handle.flush()

        while iteration_id <= n_total_iterations:

            # -------------------------------------------------------------
            # STAGE 1: ABUNDANCE ITERATION
            # -------------------------------------------------------------
            if next_stage == "abundance":
                LOGGER.info("Starting AutoSpecFit-Abund iteration %d", iteration_id)

                if iteration_id == 1:
                    model_paths = first_iteration_model_paths(
                        config, current_stellar_parameters, species
                    )
                    turbospectrum_commands = first_iteration_turbospectrum_commands(
                        config=config,
                        stellar_parameters=current_stellar_parameters,
                        species=species,
                    )
                else:
                    previous_abundance_strings: List[str] = []
                    current_nan_replacement_notes: List[str] = []

                    for species_index, value in enumerate(
                        rounded_history[:, iteration_id - 2]
                    ):
                        element_name = species.element_names[species_index]

                        if np.isfinite(value):
                            previous_abundance_strings.append(
                                format_abundance_filename_value(value)
                            )
                        else:
                            earlier_values = rounded_history[
                                species_index, : iteration_id - 2
                            ]
                            finite_earlier_values = earlier_values[
                                np.isfinite(earlier_values)
                            ]

                            if len(finite_earlier_values) > 0:
                                replacement_value = float(finite_earlier_values[-1])
                                previous_abundance_strings.append(
                                    format_abundance_filename_value(replacement_value)
                                )
                                note = (
                                    f"Iteration {iteration_id}: {element_name} abundance "
                                    f"from iteration {iteration_id - 1} is NaN; using "
                                    f"{replacement_value:+.3f} from the most recent "
                                    f"valid previous iteration to generate models."
                                )
                            else:
                                previous_abundance_strings.append("+0.000")
                                note = (
                                    f"Iteration {iteration_id}: {element_name} abundance "
                                    f"from iteration {iteration_id - 1} is NaN and no "
                                    f"previous valid abundance exists; using +0.000 "
                                    f"to generate models."
                                )

                            LOGGER.warning(note)
                            log_handle.write(f"# {note}\n")
                            log_handle.flush()
                            current_nan_replacement_notes.append(note)
                            nan_replacement_notes.append(note)

                    append_nan_replacement_notes_to_mean_file(
                        iteration_id=iteration_id - 1,
                        notes=current_nan_replacement_notes,
                        config=config,
                    )

                    model_paths = followup_iteration_model_paths(
                        config,
                        current_stellar_parameters,
                        species,
                        previous_abundance_strings,
                    )
                    turbospectrum_commands = followup_iteration_turbospectrum_commands(
                        config=config,
                        stellar_parameters=current_stellar_parameters,
                        species=species,
                        previous_abundance_strings=previous_abundance_strings,
                    )

                results = run_iteration(
                    iteration_id=iteration_id,
                    model_paths=model_paths,
                    stellar_parameters=current_stellar_parameters,
                    species=species,
                    line_lists=line_lists,
                    lam_star=lam_star,
                    flux_star=flux_star,
                    err_flux_star=err_flux_star,
                    config=config,
                    abundance_grid=abundance_grid,
                    turbospectrum_commands=turbospectrum_commands,
                    log_handle=log_handle,
                )

                mean_history[:, iteration_id - 1] = [
                    result.mean_abundance for result in results
                ]
                rounded_history[:, iteration_id - 1] = [
                    result.rounded_mean_abundance for result in results
                ]
                current_abundance_errors = species_abundance_errors_from_iteration(
                    results
                )

                update_abundance_history_table(
                    path=abundance_history_path,
                    iteration_id=iteration_id,
                    species=species,
                    abundances=mean_history[:, iteration_id - 1],
                    rounded_abundances=rounded_history[:, iteration_id - 1],
                    random_errors=current_abundance_errors,
                )

                # Abundance iteration N is followed by the refinement that
                # produces parameter iteration N+1. If convergence is accepted,
                # the dedicated final abundance is also iteration N+1 and no
                # parameter refinement follows it.
                if config.refine_parameters_after_each_iteration:
                    next_stage = "parameter"
                else:
                    next_stage = "convergence"

                save_restart_checkpoint(
                    config,
                    next_stage=next_stage,
                    iteration_id=iteration_id,
                    current_stellar_parameters=current_stellar_parameters,
                    mean_history=mean_history,
                    rounded_history=rounded_history,
                    last_parameter_errors=last_parameter_errors,
                    last_real_parameter_values=last_real_parameter_values,
                    abundance_errors=current_abundance_errors,
                    parameter_converged_for_next_iteration=True,
                    nan_replacement_notes=nan_replacement_notes,
                    last_parameter_consistency_shifts=last_parameter_consistency_shifts,
                )

            # -------------------------------------------------------------
            # STAGE 2: PARAMETER REFINEMENT
            # -------------------------------------------------------------
            if next_stage == "parameter":
                used_parameters = current_stellar_parameters
                parameter_iteration_id = iteration_id + 1

                refinement = perform_parameter_refinement(
                    parameter_refiner=parameter_refiner,
                    iteration_id=parameter_iteration_id,
                    stellar_parameters=used_parameters,
                    # The supplied parameter refiner does not require in-memory abundance line objects;
                    # all necessary abundance values are checkpointed below.
                    iteration_results=[],
                    mean_abundances=mean_history[:, iteration_id - 1],
                    rounded_abundances=rounded_history[:, iteration_id - 1],
                    species=species,
                    line_lists=line_lists,
                    lam_star=lam_star,
                    flux_star=flux_star,
                    err_flux_star=err_flux_star,
                    config=config,
                )

                change_converged = parameter_change_is_converged(
                    used_parameters,
                    refinement.stellar_parameters,
                    config,
                )
                parameter_converged_for_next_iteration = bool(
                    refinement.converged or change_converged
                )

                write_parameter_history_row(
                    legacy_parameter_history_path,
                    parameter_iteration_id,
                    used_parameters,
                    refinement.stellar_parameters,
                    refinement.converged,
                    change_converged,
                    refinement.note,
                )

                # Every individual parameter sub-step is already rounded to
                # its nearest adopted grid value. Apply one final grid-rounding
                # safeguard to the complete parameter set before carrying it
                # into the next abundance iteration.
                current_stellar_parameters = round_all_stellar_parameters_to_grids(
                    config,
                    refinement.stellar_parameters,
                )
                assert_canonical_stellar_parameter_strings(
                    current_stellar_parameters
                )

                update_parameter_history_table(
                    path=parameter_history_path,
                    iteration_id=parameter_iteration_id,
                    stellar_parameters=current_stellar_parameters,
                    real_parameter_values=refinement.real_parameter_values,
                    parameter_errors=refinement.parameter_errors,
                    parameter_consistency_shifts=refinement.parameter_consistency_shifts,
                )

                if refinement.parameter_errors:
                    last_parameter_errors = dict(refinement.parameter_errors)
                if refinement.real_parameter_values:
                    last_real_parameter_values = dict(
                        refinement.real_parameter_values
                    )
                if refinement.parameter_consistency_shifts:
                    last_parameter_consistency_shifts = dict(
                        refinement.parameter_consistency_shifts
                    )

                LOGGER.info(
                    "Parameter iteration %d, produced after abundance iteration %d: "
                    "vmic %s -> %s, [M/H] %s -> %s, logg %s -> %s, "
                    "Teff %s -> %s, [alpha/Fe] %s -> %s",
                    parameter_iteration_id,
                    iteration_id,
                    used_parameters.vmic,
                    current_stellar_parameters.vmic,
                    used_parameters.metallicity,
                    current_stellar_parameters.metallicity,
                    used_parameters.logg,
                    current_stellar_parameters.logg,
                    used_parameters.teff,
                    current_stellar_parameters.teff,
                    used_parameters.alpha,
                    current_stellar_parameters.alpha,
                )

                next_stage = "convergence"
                save_restart_checkpoint(
                    config,
                    next_stage=next_stage,
                    iteration_id=iteration_id,
                    current_stellar_parameters=current_stellar_parameters,
                    mean_history=mean_history,
                    rounded_history=rounded_history,
                    last_parameter_errors=last_parameter_errors,
                    last_real_parameter_values=last_real_parameter_values,
                    abundance_errors=current_abundance_errors,
                    parameter_converged_for_next_iteration=parameter_converged_for_next_iteration,
                    nan_replacement_notes=nan_replacement_notes,
                    last_parameter_consistency_shifts=last_parameter_consistency_shifts,
                )
                clear_parameter_progress(config)

            # -------------------------------------------------------------
            # STAGE 3: CONVERGENCE / FINALIZATION
            # -------------------------------------------------------------
            if next_stage == "convergence":

                # Iteration 1 is never the final abundance convergence comparison.
                if iteration_id == 1:
                    iteration_id = 2
                    next_stage = "abundance"
                    save_restart_checkpoint(
                        config,
                        next_stage=next_stage,
                        iteration_id=iteration_id,
                        current_stellar_parameters=current_stellar_parameters,
                        mean_history=mean_history,
                        rounded_history=rounded_history,
                        last_parameter_errors=last_parameter_errors,
                        last_real_parameter_values=last_real_parameter_values,
                        abundance_errors=current_abundance_errors,
                        parameter_converged_for_next_iteration=parameter_converged_for_next_iteration,
                        nan_replacement_notes=nan_replacement_notes,
                        last_parameter_consistency_shifts=last_parameter_consistency_shifts,
                    )
                    continue

                change = np.abs(
                    mean_history[:, iteration_id - 1]
                    - mean_history[:, iteration_id - 2]
                )

                (
                    converged,
                    non_converged_indices,
                    active_tolerance,
                    convergence_mode,
                ) = evaluate_convergence_status(
                    change,
                    iteration_id,
                    config,
                )

                if (
                    converged
                    and config.refine_parameters_after_each_iteration
                    and iteration_id < n_total_iterations
                    and not parameter_converged_for_next_iteration
                ):
                    LOGGER.info(
                        "Abundance convergence reached at iteration %d, but stellar "
                        "parameters changed beyond tolerance; continuing with the "
                        "refined atmosphere.",
                        iteration_id,
                    )
                    converged = False

                reached_maximum_iteration = iteration_id == n_total_iterations
                forced_final_iteration = False

                if not converged and reached_maximum_iteration:
                    forced_final_iteration = True
                    active_tolerance = config.late_convergence_tolerance
                    convergence_mode = "maximum-iteration finalization"
                    non_converged_indices = np.where(
                        (~np.isfinite(change))
                        | (change > active_tolerance)
                    )[0].astype(int).tolist()
                    converged = True

                if converged:
                    final_not_rounded = mean_history[:, iteration_id - 1].copy()
                    final_rounded = rounded_history[:, iteration_id - 1].copy()

                    if non_converged_indices:
                        if forced_final_iteration:
                            context = (
                                f"did not satisfy the final convergence tolerance "
                                f"({active_tolerance:.3f} dex) at the maximum iteration"
                            )
                        else:
                            context = (
                                f"was treated as oscillating under the "
                                f"{convergence_mode} criterion "
                                f"({active_tolerance:.3f} dex)"
                            )

                        apply_late_history_statistics(
                            final_not_rounded=final_not_rounded,
                            final_rounded=final_rounded,
                            indices=non_converged_indices,
                            mean_history=mean_history,
                            iteration_id=iteration_id,
                            species=species,
                            config=config,
                            log_handle=log_handle,
                            notes=nan_replacement_notes,
                            context=context,
                        )

                    if forced_final_iteration:
                        note = (
                            f"Maximum iteration {iteration_id} reached before a "
                            f"tiered convergence criterion was satisfied."
                        )
                    elif non_converged_indices:
                        note = (
                            f"Convergence accepted at iteration {iteration_id} "
                            f"under the {convergence_mode} criterion."
                        )
                    else:
                        note = (
                            f"Convergence accepted at iteration {iteration_id}: "
                            f"all species satisfied the active tolerance."
                        )

                    LOGGER.info(note)
                    log_handle.write(f"# {note}\n")
                    log_handle.flush()
                    nan_replacement_notes.append(note)

                    # Record final atmospheric parameters and their uncertainties.
                    write_final_parameter_table(
                        stellar_parameters=current_stellar_parameters,
                        parameter_errors=last_parameter_errors,
                        real_parameter_values=last_real_parameter_values,
                        config=config,
                    )

                    # ---------------------------------------------------------
                    # DEDICATED FINAL ABUNDANCE DETERMINATION
                    # ---------------------------------------------------------
                    # Freeze the final stellar parameters above, then re-measure the
                    # abundances once more. No parameter-refinement stage follows.
                    final_seed_strings: List[str] = []
                    for species_index, value in enumerate(final_rounded):
                        element_name = species.element_names[species_index]
                        if np.isfinite(value):
                            final_seed_strings.append(
                                format_abundance_filename_value(float(value))
                            )
                        else:
                            earlier_values = rounded_history[species_index, :iteration_id]
                            finite_earlier_values = earlier_values[np.isfinite(earlier_values)]
                            if len(finite_earlier_values) > 0:
                                replacement_value = float(finite_earlier_values[-1])
                                final_seed_strings.append(
                                    format_abundance_filename_value(replacement_value)
                                )
                                replacement_note = (
                                    f"Final abundance fit: {element_name} seed abundance is NaN; "
                                    f"using {replacement_value:+.3f} from the most recent finite iterative abundance."
                                )
                            else:
                                final_seed_strings.append("+0.000")
                                replacement_note = (
                                    f"Final abundance fit: {element_name} seed abundance is NaN and no "
                                    f"finite previous abundance exists; using +0.000."
                                )
                            LOGGER.warning(replacement_note)
                            log_handle.write(f"# {replacement_note}\n")
                            log_handle.flush()
                            nan_replacement_notes.append(replacement_note)

                    final_abundance_iteration_id = iteration_id + 1
                    LOGGER.info(
                        "Starting dedicated FINAL abundance determination with fixed stellar "
                        "parameters after iterative cycle %d.", iteration_id,
                    )
                    final_model_paths = followup_iteration_model_paths(
                        config=config,
                        stellar_parameters=current_stellar_parameters,
                        species=species,
                        previous_abundance_strings=final_seed_strings,
                    )
                    final_turbospectrum_commands = followup_iteration_turbospectrum_commands(
                        config=config,
                        stellar_parameters=current_stellar_parameters,
                        species=species,
                        previous_abundance_strings=final_seed_strings,
                    )
                    final_results = run_iteration(
                        iteration_id=final_abundance_iteration_id,
                        model_paths=final_model_paths,
                        stellar_parameters=current_stellar_parameters,
                        species=species,
                        line_lists=line_lists,
                        lam_star=lam_star,
                        flux_star=flux_star,
                        err_flux_star=err_flux_star,
                        config=config,
                        abundance_grid=abundance_grid,
                        turbospectrum_commands=final_turbospectrum_commands,
                        log_handle=log_handle,
                    )
                    final_not_rounded = np.asarray(
                        [result.mean_abundance for result in final_results], dtype=float
                    )
                    final_rounded = np.asarray(
                        [result.rounded_mean_abundance for result in final_results], dtype=float
                    )
                    current_abundance_errors = species_abundance_errors_from_iteration(final_results)
                    update_abundance_history_table(
                        path=abundance_history_path,
                        iteration_id=final_abundance_iteration_id,
                        species=species,
                        abundances=final_not_rounded,
                        rounded_abundances=final_rounded,
                        random_errors=current_abundance_errors,
                    )
                    LOGGER.info(
                        "Dedicated final abundance determination complete. No further "
                        "stellar-parameter refinement will be performed."
                    )

                    # Propagate each atmospheric-parameter uncertainty into the
                    # elemental abundances one parameter at a time.
                    (
                        systematic_errors,
                        total_abundance_errors,
                        per_parameter_systematics,
                    ) = run_systematic_abundance_error_analysis(
                        final_stellar_parameters=current_stellar_parameters,
                        parameter_errors=last_parameter_errors,
                        final_abundances=final_not_rounded,
                        random_abundance_errors=current_abundance_errors,
                        species=species,
                        line_lists=line_lists,
                        lam_star=lam_star,
                        flux_star=flux_star,
                        err_flux_star=err_flux_star,
                        config=config,
                    )

                    write_final_abundance_table(
                        final_not_rounded=final_not_rounded,
                        final_rounded=final_rounded,
                        final_errors=current_abundance_errors,
                        final_stellar_parameters=current_stellar_parameters,
                        species=species,
                        config=config,
                        nan_replacement_notes=nan_replacement_notes,
                        per_parameter_systematics=per_parameter_systematics,
                        systematic_errors=systematic_errors,
                        total_errors=total_abundance_errors,
                    )
                    save_restart_checkpoint(
                        config,
                        next_stage="finished",
                        iteration_id=iteration_id,
                        current_stellar_parameters=current_stellar_parameters,
                        mean_history=mean_history,
                        rounded_history=rounded_history,
                        last_parameter_errors=last_parameter_errors,
                        last_real_parameter_values=last_real_parameter_values,
                        abundance_errors=current_abundance_errors,
                        parameter_converged_for_next_iteration=parameter_converged_for_next_iteration,
                        nan_replacement_notes=nan_replacement_notes,
                        last_parameter_consistency_shifts=last_parameter_consistency_shifts,
                    )
                    return

                # Not converged: advance to the next abundance iteration.
                iteration_id += 1
                next_stage = "abundance"
                save_restart_checkpoint(
                    config,
                    next_stage=next_stage,
                    iteration_id=iteration_id,
                    current_stellar_parameters=current_stellar_parameters,
                    mean_history=mean_history,
                    rounded_history=rounded_history,
                    last_parameter_errors=last_parameter_errors,
                    last_real_parameter_values=last_real_parameter_values,
                    abundance_errors=current_abundance_errors,
                    parameter_converged_for_next_iteration=parameter_converged_for_next_iteration,
                    nan_replacement_notes=nan_replacement_notes,
                    last_parameter_consistency_shifts=last_parameter_consistency_shifts,
                )
                continue

        raise RuntimeError("ASF iteration loop ended unexpectedly.")


