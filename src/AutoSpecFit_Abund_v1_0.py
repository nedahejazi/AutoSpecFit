@dataclass(frozen=True)
class StellarParameters:
    """Fixed stellar parameters used by ASF and Turbospectrum.

    ASF-Abund v1.0 treats these quantities as user-supplied inputs. They are
    used to construct synthetic-spectrum filenames and Turbospectrum execution
    strings. The current release does not optimize these parameters.
    """

    teff: str = "3700"
    logg: str = "+4.5"
    metallicity: str = "+0.20"
    alpha: str = "+0.00"
    vmic: str = "1.00"

    def base_model_stem(self) -> str:
        """Return the common filename stem for all synthetic spectra."""
        return (
            f"t{self.teff}_g{self.logg}_z{self.metallicity}"
            f"_a{self.alpha}_v{self.vmic}"
        )

    def parallel_parameter_string(self) -> str:
        """Construct the GNU-parallel parameter string for the fixed stellar parameters."""
        return (
            f" ::: {self.teff} ::: {self.logg} ::: {self.metallicity}"
            f" ::: {self.alpha} ::: {self.vmic}"
        )


@dataclass(frozen=True)
class SpeciesConfig:
    """Species and element labels used by the abundance pipeline.

    Users may modify or extend these lists to include additional atomic or
    molecular species depending on the wavelength coverage, line lists, target
    stars, and scientific goals of the analysis.

    When adding a new species, the corresponding species input file,
    Turbospectrum abundance grid, and synthetic spectra must also be available.
    """

    element_codes: Tuple[str, ...] = (
        "x08", "x12", "x13", "x19", "x20", "x22", "x25", "x26"
    )
    element_names: Tuple[str, ...] = (
        "O", "Mg", "Al", "K", "Ca", "Ti", "Mn", "Fe"
    )
    species_names: Tuple[str, ...] = (
        "OH", "Mg", "Al", "K", "Ca", "Ti", "Mn", "Fe"
    )

    def __post_init__(self) -> None:
        """Ensure all species-related arrays have the same length."""
        n_codes = len(self.element_codes)
        if len(self.element_names) != n_codes or len(self.species_names) != n_codes:
            raise ValueError("element_codes, element_names, and species_names must match in length.")

    @property
    def n_species(self) -> int:
        """Number of species/elements measured by the pipeline."""
        return len(self.species_names)


