@dataclass(frozen=True)
class StellarParameters:
    """Stellar atmospheric/synthesis parameters used by ASF and Turbospectrum.

    In ASF v2.0, these values provide the starting atmosphere and are updated
    during the iterative parameter-refinement cycles for Teff, log g, [M/H],
    [alpha/Fe], and vmic.  The stored strings are also used consistently in
    synthetic-spectrum filenames and Turbospectrum execution commands.
    """

    teff: str = "3700"
    logg: str = "+4.7"
    metallicity: str = "+0.20"
    alpha: str = "+0.00"
    vmic: str = "1.00"

    def base_model_stem(self) -> str:
        """Return the common filename stem for all synthetic spectra."""
        return (
            f"t{self.teff}_g{self.logg}_z{self.metallicity}"
            f"_a{self.alpha}_v{self.vmic}"
        )

    def parallel_parameter_string(self) -> str:
        """Construct the GNU-parallel argument string for the current stellar parameters."""
        return (
            f" ::: {self.teff} ::: {self.logg} ::: {self.metallicity}"
            f" ::: {self.alpha} ::: {self.vmic}"
        )


