    #
    # All abundance-convergence stages use the same 0.05 dex tolerance.
    #
    # Iterations 2-6:
    #     strict convergence is accepted only when all species change by
    #     <= 0.05 dex between consecutive iterations.
    #
    # Iterations 7-8:
    #     convergence is accepted when all species, or all but one species,
    #     change by <= 0.05 dex. If one species is still non-converged, its
    #     final abundance is set to the median of its final three finite
    #     iteration abundances.
    #
    # Iterations 9-15:
    #     convergence is accepted when all species satisfy <= 0.05 dex, or when
    #     at most two species remain above 0.05 dex, provided that:
    #       (1) one of them may exceed 0.05 dex without an upper limit; and
    #       (2) the second, if present, must be > 0.05 dex and <= 0.10 dex.
    #     Any species above 0.05 dex is treated as non-converged/oscillating and
    #     its final abundance is estimated from the median of its final three
    #     finite iteration abundances.
