def stellar_parameters_to_dict(parameters: StellarParameters) -> Dict[str, str]:
    return {
        "teff": parameters.teff,
        "logg": parameters.logg,
        "metallicity": parameters.metallicity,
        "alpha": parameters.alpha,
        "vmic": parameters.vmic,
    }


def stellar_parameters_from_dict(values: Dict[str, str]) -> StellarParameters:
    return StellarParameters(
        teff=str(values["teff"]),
        logg=str(values["logg"]),
        metallicity=str(values["metallicity"]),
        alpha=str(values.get("alpha", "+0.00")),
        vmic=str(values.get("vmic", "1.00")),
    )


def _atomic_json_write(path: Path, payload: Dict) -> None:
    """
    Write a human-readable text checkpoint atomically.

    The body uses indented JSON syntax because it is both easy to read in a text
    editor and safe/reliable for ASF to parse automatically on restart.
    """
    path = Path(path)
    tmp_path = path.with_suffix(path.suffix + ".tmp")
    with open(tmp_path, "w") as handle:
        handle.write("# AutoSpecFit restart checkpoint\n")
        json.dump(payload, handle, indent=2, allow_nan=True)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(tmp_path, path)


def save_restart_checkpoint(
    config: AutoSpecFitConfig,
    *,
    next_stage: str,
    iteration_id: int,
    current_stellar_parameters: StellarParameters,
    mean_history: np.ndarray,
    rounded_history: np.ndarray,
    last_parameter_errors: Dict[str, float],
    last_real_parameter_values: Dict[str, float],
    abundance_errors: np.ndarray,
    parameter_converged_for_next_iteration: bool,
    nan_replacement_notes: List[str],
    last_parameter_consistency_shifts: Optional[Dict[str, float]] = None,
) -> None:
    """
    Save everything needed to continue the ASF pipeline.

    next_stage values:
        "abundance"   -> run abundance iteration ``iteration_id`` next
        "parameter"   -> run parameter cycle after abundance iteration ``iteration_id``
        "convergence" -> abundance + parameter work for ``iteration_id`` is complete;
                         only convergence/finalization remains
        "finished"    -> final products were written
    """
    payload = {
        "version": 1,
        "next_stage": str(next_stage),
        "iteration_id": int(iteration_id),
        "current_stellar_parameters": stellar_parameters_to_dict(
            current_stellar_parameters
        ),
        "mean_history": np.asarray(mean_history, dtype=float).tolist(),
        "rounded_history": np.asarray(rounded_history, dtype=float).tolist(),
        "last_parameter_errors": {
            key: float(value) if np.isfinite(value) else None
            for key, value in last_parameter_errors.items()
        },
        "last_real_parameter_values": {
            key: float(value) if np.isfinite(value) else None
            for key, value in last_real_parameter_values.items()
        },
        "last_parameter_consistency_shifts": {
            key: float(value) if np.isfinite(value) else None
            for key, value in (last_parameter_consistency_shifts or {}).items()
        },
        "abundance_errors": [
            float(value) if np.isfinite(value) else None
            for value in np.asarray(abundance_errors, dtype=float)
        ],
        "parameter_converged_for_next_iteration": bool(
            parameter_converged_for_next_iteration
        ),
        "nan_replacement_notes": list(nan_replacement_notes),
    }
    checkpoint_path = Path(config.output_dir) / config.checkpoint_file
    _atomic_json_write(checkpoint_path, payload)
    LOGGER.info(
        "Restart checkpoint saved | next_stage=%s | iteration=%d | %s",
        next_stage,
        iteration_id,
        checkpoint_path,
    )



def initialize_fresh_start_once(config: AutoSpecFitConfig) -> None:
    """
    Start this analysis from iteration 1 exactly once.

    If the fresh-start marker does not exist, remove any old restart/progress
    checkpoint files and create the marker. Subsequent relaunches keep the
    marker and therefore resume from the newly written checkpoint files.
    """
    marker_path = Path(config.output_dir) / config.fresh_start_marker_file
    if marker_path.exists():
        return

    for filename in (config.checkpoint_file, config.parameter_progress_file):
        path = Path(config.output_dir) / filename
        if path.exists():
            path.unlink()

    with open(marker_path, "w") as handle:
        handle.write(
            "Fresh ASF run initialized. Existing restart checkpoints were cleared.\n"
        )

    LOGGER.warning(
        "Fresh-start marker created. ASF will begin from abundance iteration 1."
    )


def load_restart_checkpoint(
    config: AutoSpecFitConfig,
    species: SpeciesConfig,
    n_total_iterations: int,
) -> Optional[Dict]:
    checkpoint_path = Path(config.output_dir) / config.checkpoint_file

    if not config.resume_from_checkpoint or not checkpoint_path.exists():
        return None

    with open(checkpoint_path, "r") as handle:
        content = "".join(
            line for line in handle if not line.lstrip().startswith("#")
        )
    payload = json.loads(content)

    if int(payload.get("version", 0)) != 1:
        raise RuntimeError(
            f"Unsupported ASF restart checkpoint version in {checkpoint_path}"
        )

    mean_history = np.asarray(payload["mean_history"], dtype=float)
    rounded_history = np.asarray(payload["rounded_history"], dtype=float)

    expected_shape = (species.n_species, n_total_iterations)
    if mean_history.shape != expected_shape or rounded_history.shape != expected_shape:
        raise RuntimeError(
            "Checkpoint history shape does not match the current ASF configuration: "
            f"checkpoint={mean_history.shape}, expected={expected_shape}"
        )

    def restore_float_dict(values: Dict[str, Optional[float]]) -> Dict[str, float]:
        return {
            key: (np.nan if value is None else float(value))
            for key, value in values.items()
        }

    payload["mean_history_array"] = mean_history
    payload["rounded_history_array"] = rounded_history
    payload["parameter_errors_dict"] = restore_float_dict(
        payload.get("last_parameter_errors", {})
    )
    payload["real_parameter_values_dict"] = restore_float_dict(
        payload.get("last_real_parameter_values", {})
    )
    payload["parameter_consistency_shifts_dict"] = restore_float_dict(
        payload.get("last_parameter_consistency_shifts", {})
    )
    payload["abundance_errors_array"] = np.asarray(
        [
            np.nan if value is None else float(value)
            for value in payload.get("abundance_errors", [])
        ],
        dtype=float,
    )

    LOGGER.warning(
        "Restart checkpoint found. ASF will resume from stage '%s' at iteration %d.",
        payload["next_stage"],
        int(payload["iteration_id"]),
    )
    return payload


