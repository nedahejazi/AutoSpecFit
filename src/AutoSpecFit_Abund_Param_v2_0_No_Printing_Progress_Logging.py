def load_parameter_progress(
    config: AutoSpecFitConfig,
    iteration_id: int,
    starting_parameters: StellarParameters,
) -> Optional[Dict]:
    """Return an unfinished parameter-cycle checkpoint when it matches this cycle."""
    path = Path(config.output_dir) / config.parameter_progress_file
    if not config.resume_from_checkpoint or not path.exists():
        return None

    with open(path, "r") as handle:
        content = "".join(
            line for line in handle if not line.lstrip().startswith("#")
        )
    payload = json.loads(content)

    if int(payload.get("version", 0)) != 1:
        return None
    if int(payload.get("iteration_id", -1)) != int(iteration_id):
        return None

    # Protect against accidentally reusing a checkpoint from a different
    # atmosphere/run that happens to have the same iteration number.
    saved_start = stellar_parameters_from_dict(payload["starting_parameters"])
    if stellar_parameters_to_dict(saved_start) != stellar_parameters_to_dict(starting_parameters):
        LOGGER.warning(
            "Ignoring parameter-progress checkpoint for iteration %d because "
            "its starting atmosphere differs from the current one.",
            iteration_id,
        )
        return None

    payload["current_parameters_obj"] = stellar_parameters_from_dict(
        payload["current_parameters"]
    )
    payload["parameter_errors_dict"] = {
        key: (np.nan if value is None else float(value))
        for key, value in payload.get("parameter_errors", {}).items()
    }
    payload["real_parameter_values_dict"] = {
        key: (np.nan if value is None else float(value))
        for key, value in payload.get("real_parameter_values", {}).items()
    }
    payload["parameter_consistency_shifts_dict"] = {
        key: (np.nan if value is None else float(value))
        for key, value in payload.get("parameter_consistency_shifts", {}).items()
    }
    payload["first_pass_real_values_dict"] = {
        key: (np.nan if value is None else float(value))
        for key, value in payload.get("first_pass_real_values", {}).items()
    }

    LOGGER.warning(
        "Resuming parameter iteration %d after completed step(s): %s",
        iteration_id,
        ", ".join(payload.get("completed_steps", [])) or "none",
    )
    return payload


def clear_parameter_progress(config: AutoSpecFitConfig) -> None:
    path = Path(config.output_dir) / config.parameter_progress_file
    if path.exists():
        path.unlink()


