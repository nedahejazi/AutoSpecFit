class SpeciesIterationResult:
    """Combined abundance result for one species in one ASF iteration.

    The final species abundance is computed from accepted line-by-line
    abundances after edge rejection, conservative sigma clipping, and
    median-distance weighting.
    """

    species_name: str
    element_name: str
    line_results: List[LineFitResult]
    clipped_line_abundances: np.ndarray
    mean_abundance: float
    rounded_mean_abundance: float


