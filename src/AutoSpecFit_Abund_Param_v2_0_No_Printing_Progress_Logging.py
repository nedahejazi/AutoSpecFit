def update_abundance_history_table(
    path: Path,
    iteration_id: int,
    species: SpeciesConfig,
    abundances: np.ndarray,
    rounded_abundances: np.ndarray,
    random_errors: np.ndarray,
) -> None:
    """Update the cumulative wide-format elemental-abundance history."""
    path = Path(path)
    elements = list(species.element_names)
    if path.exists() and path.stat().st_size > 0:
        try:
            table = pd.read_csv(path, delim_whitespace=True, comment="#")
        except Exception:
            table = pd.DataFrame({"Element": elements})
    else:
        table = pd.DataFrame({"Element": elements})
    if "Element" not in table.columns:
        table.insert(0, "Element", elements)
    table = table.set_index("Element").reindex(elements)
    prefix = f"Iteration_{iteration_id}"
    table[f"{prefix}_Abundance"] = np.asarray(abundances, dtype=float)
    table[f"{prefix}_Rounded_Abundance"] = np.asarray(rounded_abundances, dtype=float)
    table[f"{prefix}_Random_Error"] = np.asarray(random_errors, dtype=float)
    table = table.reset_index()
    with open(path, "w") as handle:
        handle.write("# Cumulative elemental-abundance history for GJ205\n")
        handle.write("# Each iteration adds abundance, rounded abundance, and 1-sigma random-error columns.\n")
        table.to_csv(handle, sep=" ", index=False, float_format="%.6f", na_rep="nan")


def update_parameter_history_table(
    path: Path,
    iteration_id: int,
    stellar_parameters: StellarParameters,
    real_parameter_values: Dict[str, float],
    parameter_errors: Dict[str, float],
    parameter_consistency_shifts: Dict[str, float],
) -> None:
    """Update the cumulative wide-format atmospheric-parameter history."""
    path = Path(path)
    rows = [
        ("Teff", "teff", stellar_parameters.teff),
        ("logg", "logg", stellar_parameters.logg),
        ("[M/H]", "metallicity", stellar_parameters.metallicity),
        ("[alpha/Fe]", "alpha", stellar_parameters.alpha),
        ("vmic", "vmic", stellar_parameters.vmic),
    ]
    labels = [r[0] for r in rows]
    if path.exists() and path.stat().st_size > 0:
        try:
            table = pd.read_csv(path, delim_whitespace=True, comment="#")
        except Exception:
            table = pd.DataFrame({"Parameter": labels})
    else:
        table = pd.DataFrame({"Parameter": labels})
    if "Parameter" not in table.columns:
        table.insert(0, "Parameter", labels)
    table = table.set_index("Parameter").reindex(labels)
    prefix = f"Iteration_{iteration_id}"
    table[f"{prefix}_Real_Value"] = [real_parameter_values.get(r[1], np.nan) for r in rows]
    table[f"{prefix}_Rounded_Value"] = [float(r[2]) for r in rows]
    table[f"{prefix}_Random_Error"] = [parameter_errors.get(r[1], np.nan) for r in rows]
    table[f"{prefix}_Pass1_to_Pass2_Difference"] = [parameter_consistency_shifts.get(r[1], np.nan) for r in rows]
    table = table.reset_index()
    with open(path, "w") as handle:
        handle.write("# Cumulative atmospheric-parameter history for GJ205\n")
        handle.write("# Each iteration adds accepted real value, propagated rounded value, 1-sigma random error, and Pass-1/Pass-2 consistency difference.\n")
        table.to_csv(handle, sep=" ", index=False, float_format="%.6f", na_rep="nan")


def rebuild_history_outputs_from_restart(
    config: AutoSpecFitConfig,
    species: SpeciesConfig,
    mean_history: np.ndarray,
    rounded_history: np.ndarray,
    iteration_id: int,
    next_stage: str,
    current_abundance_errors: np.ndarray,
    current_stellar_parameters: StellarParameters,
    last_real_parameter_values: Dict[str, float],
    last_parameter_errors: Dict[str, float],
    last_parameter_consistency_shifts: Dict[str, float],
) -> None:
    """Create new cumulative history files when resuming an older run.

    Abundance values are reconstructed directly from the checkpoint arrays. Older
    random errors are unavailable in legacy checkpoints and are therefore left NaN.
    The legacy row-style parameter history is used to reconstruct propagated
    parameter values; legacy rows do not contain formal errors/real values, so those
    fields remain NaN except for the latest completed parameter cycle stored in the
    checkpoint.
    """
    abundance_path = Path(config.output_dir) / config.abundance_history_file
    parameter_path = Path(config.output_dir) / config.parameter_history_file
    legacy_path = Path(config.output_dir) / config.legacy_parameter_history_file

    if not abundance_path.exists():
        for col in range(mean_history.shape[1]):
            if np.any(np.isfinite(mean_history[:, col])):
                errors = np.full(species.n_species, np.nan)
                completed_iter = col + 1
                if completed_iter == iteration_id and next_stage in ("parameter", "convergence", "finished"):
                    errors = np.asarray(current_abundance_errors, dtype=float)
                update_abundance_history_table(
                    abundance_path, completed_iter, species,
                    mean_history[:, col], rounded_history[:, col], errors,
                )

    if not parameter_path.exists() and legacy_path.exists() and legacy_path.stat().st_size > 0:
        try:
            legacy = pd.read_csv(legacy_path, delim_whitespace=True)
            for _, row in legacy.iterrows():
                it = int(row["Iteration"])
                params = StellarParameters(
                    teff=str(row["Teff_Refined"]),
                    logg=str(row["logg_Refined"]),
                    metallicity=str(row["MH_Refined"]),
                    alpha=str(row["alpha_Refined"]),
                    vmic=str(row["vmic_Refined"]),
                )
                update_parameter_history_table(
                    parameter_path, it, params, {}, {}, {},
                )
        except Exception as exc:
            LOGGER.warning("Could not migrate legacy GJ205 parameter history: %s", exc)

    # If the checkpoint is after a completed parameter cycle, abundance
    # iteration N has produced parameter iteration N+1. Replace that parameter
    # iteration with the richer checkpointed values/errors.
    if next_stage in ("convergence", "finished"):
        update_parameter_history_table(
            parameter_path, iteration_id + 1, current_stellar_parameters,
            last_real_parameter_values, last_parameter_errors,
            last_parameter_consistency_shifts,
        )


