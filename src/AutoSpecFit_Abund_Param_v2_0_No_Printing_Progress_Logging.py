def parameter_change_is_converged(
    old_parameters: StellarParameters,
    new_parameters: StellarParameters,
    config: AutoSpecFitConfig,
) -> bool:
    """Return True when all five fitted atmospheric parameters are stable."""
    try:
        d_teff = abs(float(new_parameters.teff) - float(old_parameters.teff))
        d_logg = abs(float(new_parameters.logg) - float(old_parameters.logg))
        d_metallicity = abs(float(new_parameters.metallicity) - float(old_parameters.metallicity))
        d_alpha = abs(float(new_parameters.alpha) - float(old_parameters.alpha))
        d_vmic = abs(float(new_parameters.vmic) - float(old_parameters.vmic))
    except (TypeError, ValueError) as exc:
        raise ValueError(
            "StellarParameters.teff, logg, metallicity, alpha, and vmic must be "
            "numeric strings when iterative parameter refinement is enabled."
        ) from exc

    return (
        d_teff <= config.teff_convergence_tolerance
        and d_logg <= config.logg_convergence_tolerance
        and d_metallicity <= config.metallicity_convergence_tolerance
        and d_alpha <= config.alpha_convergence_tolerance
        and d_vmic < config.vmic_convergence_tolerance
    )


