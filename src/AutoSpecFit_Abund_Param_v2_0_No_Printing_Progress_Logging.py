    """Abundance-fit result for one selected spectral line.

    The object stores both the grid-based best abundance and the abundance
    inferred from a local parabolic fit to the chi-square curve.
    """

    species_name: str
    line_index: int
    line_center: float
    best_abundance_grid: float
    best_abundance_parabola: float
    abundance_error: float
    chi2_curve: np.ndarray

    @property
    def label(self) -> str:
        """Column label used in iteration-wide chi-square tables."""
