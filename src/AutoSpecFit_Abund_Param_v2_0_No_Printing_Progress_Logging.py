def write_final_parameter_table(
    stellar_parameters: StellarParameters,
    parameter_errors: Dict[str, float],
    real_parameter_values: Dict[str, float],
    config: AutoSpecFitConfig,
) -> None:
    """Write final stellar parameters with their random fitting errors only.

    No parameter consistency or total error is reported because the Pass-1 to
    Pass-2 change is a refinement/consistency diagnostic, not an independently
    quantified systematic uncertainty.
    """
    labels = [
        ("Teff", "teff", "K"),
        ("logg", "logg", "dex"),
        ("[M/H]", "metallicity", "dex"),
        ("[alpha/Fe]", "alpha", "dex"),
        ("vmic", "vmic", "km/s"),
    ]

    rows = []
    for display_name, key, unit in labels:
        final_value = float(real_parameter_values.get(key, np.nan))
        random_error = float(parameter_errors.get(key, np.nan))
        rows.append((display_name, final_value, unit, random_error))

    output_path = Path(config.output_dir) / config.final_parameter_file
    table = pd.DataFrame(
        rows,
        columns=[
            "Parameter",
            "Final_Value",
            "Unit",
            "Final_Random_Error",
        ],
    )
    with open(output_path, "w") as handle:
        handle.write(
            "# Final stellar parameters and 1-sigma random fitting uncertainties\n"
            "# Pass-1 to Pass-2 differences are consistency diagnostics only and\n"
            "# are not interpreted as systematic parameter uncertainties.\n"
        )
        table.to_csv(
            handle, sep=" ", index=False, float_format="%.6f", na_rep="nan"
        )
    LOGGER.info("Wrote final stellar-parameter table: %s", output_path)


def evaluate_parameter_grid(
    iteration_id: int,
    parameter_pass: int,
    parameter_name: str,
    grid: np.ndarray,
    model_paths: List[Path],
    lines: ParameterDiagnosticLines,
    lam_star: np.ndarray,
    flux_star: np.ndarray,
    err_flux_star: np.ndarray,
    config: AutoSpecFitConfig,
) -> Tuple[float, float, np.ndarray, np.ndarray, np.ndarray]:
    """
    Evaluate one atmospheric-parameter grid line by line.

    Every diagnostic line receives its own chi-square curve and preferred
    parameter.  In parameter Pass 1, internal minima are locally fit with a
    parabola and, when possible, receive a two-sided Delta-chi2=1 error.
    Minima at the adopted physical grid boundaries are retained as valid
    parameter measurements but receive NaN formal chi-square errors.

    In parameter Pass 2, exactly five original-grid points are examined around
    the rounded Pass-1 solution.  A local parabola is fitted to each valid
    line-by-line chi-square curve, exactly as in Pass 1, so that the final
    refinement has its own Delta-chi2=1 formal uncertainty.

    The adopted parameter is the simple mean of all finite individual-line
    parameter measurements.  In both Pass 1 and Pass 2, the uncertainty combines
    the line-to-line sample standard deviation and the RMS of the finite
    individual-line chi-square errors in quadrature.

    A combined total-chi-square curve is still saved for diagnostic comparison
    but is no longer used to set the adopted parameter or its uncertainty.
    """
    chi2_matrix = np.full((lines.n_lines, len(grid)), np.nan, dtype=float)

    for grid_index, (value, model_path) in enumerate(zip(grid, model_paths)):
        LOGGER.info(
            "CHI2 | PARAMETER ITERATION %d.%d | PARAMETER %s | value=%s | grid %d/%d",
            iteration_id,
            parameter_pass,
            parameter_name,
            format_parameter_value(parameter_name, value),
            grid_index + 1,
            len(grid),
        )

        for line_index in range(lines.n_lines):
            chi2_matrix[line_index, grid_index] = parameter_line_chi2_for_model(
                line_center=float(lines.line_centers[line_index]),
                radial_velocity=float(lines.radial_velocities[line_index]),
                fit_min=float(lines.fit_min_wavelengths[line_index]),
                fit_max=float(lines.fit_max_wavelengths[line_index]),
                model_path=model_path,
                lam_star=lam_star,
                flux_star=flux_star,
                err_flux_star=err_flux_star,
                config=config,
            )

    # Retain the original fair-comparison combined curve as a diagnostic only.
    common_valid_lines = np.all(np.isfinite(chi2_matrix), axis=1)
    if np.any(common_valid_lines):
        total_chi2 = np.sum(chi2_matrix[common_valid_lines, :], axis=0)
        combined_best_index = int(np.argmin(total_chi2))
        combined_best_value = float(grid[combined_best_index])
    else:
        total_chi2 = np.full(len(grid), np.nan, dtype=float)
        combined_best_value = np.nan

    line_best = np.full(lines.n_lines, np.nan, dtype=float)
    line_errors = np.full(lines.n_lines, np.nan, dtype=float)
    line_chi2_min = np.full(lines.n_lines, np.nan, dtype=float)
    line_status = np.full(lines.n_lines, "invalid", dtype=object)
    sampled_best = np.full(lines.n_lines, np.nan, dtype=float)

    for line_index in range(lines.n_lines):
        curve = chi2_matrix[line_index, :]

        finite = np.isfinite(curve)
        if np.any(finite):
            finite_indices = np.where(finite)[0]
            sampled_idx = finite_indices[int(np.argmin(curve[finite]))]
            sampled_best[line_index] = float(grid[sampled_idx])

        (
            line_best[line_index],
            line_errors[line_index],
            line_status[line_index],
            line_chi2_min[line_index],
        ) = estimate_individual_line_parameter(grid, curve)

    (
        adopted_value,
        line_std,
        chi2_rms,
        final_error,
        n_line_values,
        n_chi2_errors,
    ) = combine_individual_line_parameter_results(line_best, line_errors)

    if not np.isfinite(adopted_value):
        raise RuntimeError(
            f"No valid individual-line {parameter_name} measurements were obtained."
        )

    # Save the original grid-by-grid chi-square matrix.
    curve_output = {
        parameter_name: grid,
        "total_chi2_diagnostic": total_chi2,
    }
    for line_index in range(lines.n_lines):
        number = int(lines.line_numbers[line_index])
        label = str(lines.species_labels[line_index])
        curve_output[f"line_{number}_{label}_chi2"] = chi2_matrix[line_index, :]

    curve_path = Path(config.output_dir) / config.current_parameter_chi2_file
    with open(curve_path, "w") as handle:
        handle.write(
            f"# Stage: PARAMETER ITERATION\n# Iteration: {iteration_id}\n"
            f"# Parameter_Pass: {parameter_pass}\n# Parameter: {parameter_name}\n"
        )
        pd.DataFrame(curve_output).to_csv(
            handle, sep=" ", index=False, float_format="%.8f", na_rep="nan"
        )

    # Save one row per diagnostic line with its independent parameter result.
    result_path = Path(config.output_dir) / config.current_parameter_line_result_file

    result_table = pd.DataFrame(
        {
            "Line_Number": lines.line_numbers.astype(int),
            "Species": lines.species_labels.astype(str),
            "Line_Center": lines.line_centers.astype(float),
            "Sampled_Best": sampled_best,
            "Best_Parameter": line_best,
            "Chi2_Min": line_chi2_min,
            "Chi2_Error": line_errors,
            "Status": line_status,
        }
    )
    with open(result_path, "w") as handle:
        handle.write(
            f"# Stage: PARAMETER ITERATION\n# Iteration: {iteration_id}\n"
            f"# Parameter_Pass: {parameter_pass}\n# Parameter: {parameter_name}\n"
        )
        result_table.to_csv(
            handle, sep=" ", index=False, float_format="%.8f", na_rep="nan"
        )

    # Append the ensemble statistics as comments.
    with open(result_path, "a") as handle:
        handle.write("\n# Individual-line parameter summary\n")
        handle.write(f"# Mean_Parameter {adopted_value:.8f}\n")
        handle.write("# Fit_Method local_parabola_for_internal_minima\n")
        handle.write(
            f"# Line_to_Line_Std "
            f"{line_std if np.isfinite(line_std) else np.nan:.8f}\n"
        )
        handle.write(
            f"# RMS_Individual_Chi2_Error "
            f"{chi2_rms if np.isfinite(chi2_rms) else np.nan:.8f}\n"
        )
        handle.write(
            f"# Final_Error "
            f"{final_error if np.isfinite(final_error) else np.nan:.8f}\n"
        )
        handle.write(f"# N_Line_Values {n_line_values}\n")
        handle.write(f"# N_Finite_Chi2_Errors {n_chi2_errors}\n")
        handle.write(
            f"# N_Lower_Edge "
            f"{int(np.sum(np.isin(line_status, ['lower_edge', 'lower_edge_sampled'])))}\n"
        )
        handle.write(
            f"# N_Upper_Edge "
            f"{int(np.sum(np.isin(line_status, ['upper_edge', 'upper_edge_sampled'])))}\n"
        )
        handle.write(
            f"# Combined_Chi2_Best_Diagnostic "
            f"{combined_best_value if np.isfinite(combined_best_value) else np.nan:.8f}\n"
        )

    LOGGER.info(
        "PARAMETER RESULT | iteration %d.%d | %s mean=%.6f | "
        "line std=%s | chi2 RMS=%s | final error=%s | "
        "%d line values, %d finite formal errors",
        iteration_id,
        parameter_pass,
        parameter_name,
        adopted_value,
        "nan" if not np.isfinite(line_std) else f"{line_std:.6f}",
        "nan" if not np.isfinite(chi2_rms) else f"{chi2_rms:.6f}",
        "nan" if not np.isfinite(final_error) else f"{final_error:.6f}",
        n_line_values,
        n_chi2_errors,
    )

    LOGGER.info(
        "Edge minima retained for scatter | iteration %d | %s | "
        "lower=%d upper=%d",
        iteration_id,
        parameter_name,
        int(np.sum(np.isin(line_status, ["lower_edge", "lower_edge_sampled"]))),
        int(np.sum(np.isin(line_status, ["upper_edge", "upper_edge_sampled"]))),
    )

    if np.isfinite(combined_best_value):
        LOGGER.info(
            "Combined-chi2 diagnostic only | iteration %d | %s=%s",
            iteration_id,
            parameter_name,
            format_parameter_value(parameter_name, combined_best_value),
        )

    return adopted_value, final_error, total_chi2, chi2_matrix, line_best


def run_one_parameter_refinement_step(
    iteration_id: int,
    parameter_pass: int,
    parameter_name: str,
    diagnostic_line_numbers: Optional[Iterable[int]],
    stellar_parameters: StellarParameters,
    fixed_abundances: Dict[str, str],
    all_parameter_lines: ParameterDiagnosticLines,
    lam_star: np.ndarray,
    flux_star: np.ndarray,
    err_flux_star: np.ndarray,
    config: AutoSpecFitConfig,
    selected_lines_override: Optional[ParameterDiagnosticLines] = None,
    grid_override: Optional[np.ndarray] = None,
) -> Tuple[StellarParameters, float, float]:
    """
    Generate the TS grid, fit every selected diagnostic line independently,
    adopt the arithmetic mean line parameter, and return the empirical+formal
    uncertainty.

    ``selected_lines_override`` is used for dynamic selections such as all
    lines for vmic and Species-column alpha-element selection.
    """
    grid = (
        parameter_grid(config, parameter_name)
        if grid_override is None
        else np.asarray(grid_override, dtype=float)
    )
    if len(grid) == 0:
        raise ValueError(f"Empty parameter grid for {parameter_name}.")

    if selected_lines_override is not None:
        selected_lines = selected_lines_override
    else:
        if diagnostic_line_numbers is None:
            raise ValueError(
                f"No diagnostic lines were provided for parameter {parameter_name}."
            )
        selected_lines = all_parameter_lines.select(diagnostic_line_numbers)

    model_paths = build_parameter_model_paths(
        config=config,
        stellar_parameters=stellar_parameters,
        fixed_abundances=fixed_abundances,
        parameter_name=parameter_name,
        grid=grid,
    )

    command_batches = build_parameter_turbospectrum_command_batches(
        config=config,
        stellar_parameters=stellar_parameters,
        fixed_abundances=fixed_abundances,
        parameter_name=parameter_name,
        grid=grid,
    )

    run_parameter_ts = config.run_parameter_ts_by_iteration.get(
        iteration_id,
        config.run_turbospectrum,
    )
    missing_before_submission = require_models_or_ts_enabled(
        [model_paths],
        run_parameter_ts,
        f"Parameter iteration {iteration_id}.{parameter_pass} | {parameter_name}",
    )

    if run_parameter_ts:
        if missing_before_submission:
            LOGGER.info(
                "Parameter iteration %d.%d | %s: %d required model(s) are missing "
                "or empty; submitting Turbospectrum for missing models.",
                iteration_id,
                parameter_pass,
                parameter_name,
                len(missing_before_submission),
            )
        for runner, command in command_batches:
            LOGGER.info(
                "Parameter refinement iteration %d | %s | TS runner: %s",
                iteration_id,
                parameter_name,
                runner,
            )
            run_turbospectrum_command(
                command=command,
                runner=runner,
                execution_prefix=config.turbospectrum_execution_prefix,
            )
    else:
        LOGGER.info(
            "Parameter refinement iteration %d: skipping TS launch for %s; "
            "using existing models.",
            iteration_id,
            parameter_name,
        )

    wait_for_model_files([model_paths], config)

    (
        adopted_value,
        parameter_error,
        _total_chi2,
        _chi2_matrix,
        _line_best,
    ) = evaluate_parameter_grid(
        iteration_id=iteration_id,
        parameter_pass=parameter_pass,
        parameter_name=parameter_name,
        grid=grid,
        model_paths=model_paths,
        lines=selected_lines,
        lam_star=lam_star,
        flux_star=flux_star,
        err_flux_star=err_flux_star,
        config=config,
    )

    # The continuous parabolic best-fit value is retained as the REAL reported
    # result and is used for the Pass-2 consistency test and uncertainty.
    #
    # Before ANY result is propagated to the next parameter/abundance step,
    # however, it is rounded to the appropriate synthesis grid.  Pass 1 rounds
    # to the MAIN grid.  An accepted Pass-2 result rounds to the nearest point
    # on its five-point LOCAL Pass-2 grid, restricted entirely to the main
    # Pass-1 grid.  Thus the scientific fit remains continuous,
    # while every atmosphere/synthetic-spectrum calculation receives a grid-
    # compatible parameter value.
    if parameter_pass == 2 and grid_override is not None:
        propagation_grid = np.asarray(grid, dtype=float)
        propagation_index = int(
            np.argmin(np.abs(propagation_grid - float(adopted_value)))
        )
        propagated_value = float(propagation_grid[propagation_index])
        propagated_string = format_parameter_value(
            parameter_name, propagated_value
        )
    else:
        propagated_value, propagated_string = round_parameter_to_nearest_grid(
            config,
            parameter_name,
            adopted_value,
        )

    updated_parameters = update_one_stellar_parameter(
        stellar_parameters,
        parameter_name,
        propagated_value,
        use_exact_grid_format=True,
    )

    LOGGER.info(
        "PARAMETER RESULT | iteration %d.%d | %s real=%s +/- %s | "
        "ROUNDED VALUE FOR NEXT STEP=%s",
        iteration_id,
        parameter_pass,
        parameter_name,
        "nan" if not np.isfinite(adopted_value) else f"{adopted_value:.6f}",
        "nan" if not np.isfinite(parameter_error) else f"{parameter_error:.6f}",
        propagated_string,
    )

    return updated_parameters, parameter_error, adopted_value


def gj205_parameter_refiner(
    iteration_id: int,
    stellar_parameters: StellarParameters,
    iteration_results: List[SpeciesIterationResult],
    mean_abundances: np.ndarray,
    rounded_abundances: np.ndarray,
    species: SpeciesConfig,
    line_lists: List[LineList],
    lam_star: np.ndarray,
    flux_star: np.ndarray,
    err_flux_star: np.ndarray,
    config: AutoSpecFitConfig,
) -> ParameterRefinementResult:
    """Run the two-pass atmospheric-parameter refinement for the supplied example.

    ASF v2.0 fits vmic first and alpha last. The ordering of [M/H], log g, and
    Teff should be chosen for each target according to the availability, strength,
    and distinctiveness of their diagnostic lines. A parameter without a suitable
    diagnostic subset should be placed last among these three and fitted with all
    selected parameter lines.

    Pass 1 follows the target-specific diagnostic-line strategy encoded below.
    Pass 2 is a narrow verification/refinement around the Pass-1 result and uses
    all selected parameter lines for vmic, [M/H], log g, and Teff, while alpha
    remains restricted to alpha-element lines. Each parameter uses the most
    recently updated atmosphere from the preceding Pass-2 sub-step. Local grids
    are subsets of the original grids, centered after rounding the Pass-1 result
    to the nearest allowed global-grid value.
    """
    del iteration_results, line_lists

    starting_parameters = stellar_parameters
    all_parameter_lines = read_parameter_diagnostic_lines(config.parameter_line_file)
    alpha_lines = all_parameter_lines.select_species(config.alpha_species)

    fixed_abundances = fixed_abundance_map_from_iteration(
        rounded_abundances=rounded_abundances,
        mean_abundances=mean_abundances,
        species=species,
    )

    progress = load_parameter_progress(
        config=config,
        iteration_id=iteration_id,
        starting_parameters=starting_parameters,
    )

    keys = ("vmic", "metallicity", "logg", "teff", "alpha")
    completed_steps: List[str] = []
    current = starting_parameters
    parameter_errors: Dict[str, float] = {key: np.nan for key in keys}
    parameter_consistency_shifts: Dict[str, float] = {key: np.nan for key in keys}
    real_parameter_values: Dict[str, float] = {key: np.nan for key in keys}
    first_pass_real_values: Dict[str, float] = {key: np.nan for key in keys}

    if progress is not None:
        completed_steps = list(progress.get("completed_steps", []))
        current = progress["current_parameters_obj"]
        parameter_errors.update(progress.get("parameter_errors_dict", {}))
        real_parameter_values.update(progress.get("real_parameter_values_dict", {}))
        parameter_consistency_shifts.update(
            progress.get("parameter_consistency_shifts_dict", {})
        )
        first_pass_real_values.update(progress.get("first_pass_real_values_dict", {}))

    def checkpoint_step(step_name: str) -> None:
        if step_name not in completed_steps:
            completed_steps.append(step_name)
        pass_number = 2 if step_name.startswith("p2_") else 1
        write_current_parameter_table(
            iteration_id=iteration_id,
            parameter_pass=pass_number,
            completed_step=step_name,
            stellar_parameters=current,
            parameter_errors=parameter_errors,
            parameter_consistency_shifts=parameter_consistency_shifts,
            real_parameter_values=real_parameter_values,
            config=config,
        )
        save_parameter_progress(
            config,
            iteration_id=iteration_id,
            completed_steps=completed_steps,
            starting_parameters=starting_parameters,
            current_parameters=current,
            parameter_errors=parameter_errors,
            real_parameter_values=real_parameter_values,
            parameter_consistency_shifts=parameter_consistency_shifts,
            first_pass_real_values=first_pass_real_values,
        )

    def run_pass1_step(
        step_name: str,
        parameter_name: str,
        diagnostic_line_numbers: Optional[Iterable[int]] = None,
        selected_lines_override: Optional[ParameterDiagnosticLines] = None,
    ) -> None:
        nonlocal current
        if step_name in completed_steps:
            return
        current, error, real_value = run_one_parameter_refinement_step(
            iteration_id=iteration_id,
            parameter_pass=1,
            parameter_name=parameter_name,
            diagnostic_line_numbers=diagnostic_line_numbers,
            stellar_parameters=current,
            fixed_abundances=fixed_abundances,
            all_parameter_lines=all_parameter_lines,
            lam_star=lam_star,
            flux_star=flux_star,
            err_flux_star=err_flux_star,
            config=config,
            selected_lines_override=selected_lines_override,
        )
        parameter_errors[parameter_name] = error
        real_parameter_values[parameter_name] = real_value
        first_pass_real_values[parameter_name] = real_value
        checkpoint_step(step_name)

    # --------------------------- Pass 1 ---------------------------
    run_pass1_step("p1_vmic", "vmic", selected_lines_override=all_parameter_lines)
    run_pass1_step(
        "p1_metallicity", "metallicity",
        diagnostic_line_numbers=config.metallicity_diagnostic_lines,
    )
    run_pass1_step(
        "p1_logg", "logg", diagnostic_line_numbers=config.logg_diagnostic_lines
    )
    run_pass1_step(
        "p1_teff", "teff", diagnostic_line_numbers=config.teff_diagnostic_lines
    )
    run_pass1_step("p1_alpha", "alpha", selected_lines_override=alpha_lines)

    # --------------------------- Pass 2 ---------------------------
    half_widths = {
        "vmic": config.second_pass_vmic_half_width,
        "metallicity": config.second_pass_metallicity_half_width,
        "logg": config.second_pass_logg_half_width,
        "teff": config.second_pass_teff_half_width,
        "alpha": config.second_pass_alpha_half_width,
    }

    for parameter_name in keys:
        step_name = f"p2_{parameter_name}"
        if step_name in completed_steps:
            continue

        # Pass 2 is anchored to the Pass-1 result for this same parameter.
        # First round the continuous Pass-1 result to the nearest Pass-1/original
        # grid value.  Then select five consecutive points from that same grid,
        # centered on the rounded value whenever possible.  Near a grid edge,
        # shift the five-point window inward; no Pass-2 point may lie outside
        # the Pass-1 grid.
        pass1_real = first_pass_real_values.get(parameter_name, np.nan)
        if not np.isfinite(pass1_real):
            raise RuntimeError(
                f"Pass-2 {parameter_name} cannot start because its Pass-1 "
                "continuous result is unavailable in the parameter checkpoint."
            )
        pass1_rounded, pass1_rounded_string = round_parameter_to_nearest_grid(
            config, parameter_name, float(pass1_real)
        )
        LOGGER.info(
            "PASS-2 CENTER | iteration %d.2 | %s | Pass-1 real=%.6f | "
            "rounded center=%s | half-width=%g",
            iteration_id,
            parameter_name,
            float(pass1_real),
            pass1_rounded_string,
            float(half_widths[parameter_name]),
        )

        local_grid = local_parameter_grid(
            config=config,
            parameter_name=parameter_name,
            center_value=float(pass1_rounded),
            half_width=float(half_widths[parameter_name]),
        )

        # Preserve the Pass-1 formal/random error before Pass 2 is evaluated.
        # If the Pass-2 solution moves by more than one main-grid step from
        # the rounded Pass-1 center, Pass 2 is treated as inconsistent with the
        # intended local refinement.  In that case both the adopted value and
        # uncertainty for this parameter revert to Pass 1.
        pass1_error = float(parameter_errors.get(parameter_name, np.nan))

        current_after_pass2, pass2_error, pass2_real = run_one_parameter_refinement_step(
            iteration_id=iteration_id,
            parameter_pass=2,
            parameter_name=parameter_name,
            diagnostic_line_numbers=None,
            stellar_parameters=current,
            fixed_abundances=fixed_abundances,
            all_parameter_lines=all_parameter_lines,
            lam_star=lam_star,
            flux_star=flux_star,
            err_flux_star=err_flux_star,
            config=config,
            selected_lines_override=(
                alpha_lines if parameter_name == "alpha" else all_parameter_lines
            ),
            grid_override=local_grid,
        )

        full_grid = parameter_grid(config, parameter_name)
        center_index = int(np.argmin(np.abs(full_grid - float(pass1_rounded))))
        neighbor_steps: List[float] = []
        if center_index > 0:
            neighbor_steps.append(
                abs(float(full_grid[center_index]) - float(full_grid[center_index - 1]))
            )
        if center_index < len(full_grid) - 1:
            neighbor_steps.append(
                abs(float(full_grid[center_index + 1]) - float(full_grid[center_index]))
            )
        if not neighbor_steps:
            raise RuntimeError(
                f"Cannot determine one-grid-step consistency limit for {parameter_name}."
            )
        one_grid_step = float(min(neighbor_steps))

        if np.isfinite(pass2_real):
            consistency_shift = abs(float(pass2_real) - float(pass1_rounded))
        else:
            consistency_shift = np.inf
        parameter_consistency_shifts[parameter_name] = consistency_shift

        pass2_consistent = (
            np.isfinite(pass2_real)
            and consistency_shift <= one_grid_step + 1.0e-10
        )

        if pass2_consistent:
            current = current_after_pass2
            parameter_errors[parameter_name] = pass2_error
            real_parameter_values[parameter_name] = pass2_real
            LOGGER.info(
                "PASS-2 ACCEPTED | iteration %d.2 | %s | Pass-1 rounded=%s | "
                "Pass-2 real=%.6f | shift=%.6f <= one grid step %.6f | "
                "using Pass-2 error=%s",
                iteration_id,
                parameter_name,
                pass1_rounded_string,
                float(pass2_real),
                consistency_shift,
                one_grid_step,
                "nan" if not np.isfinite(pass2_error) else f"{pass2_error:.6f}",
            )
        else:
            # Keep all already accepted Pass-2 updates for the OTHER parameters,
            # but restore this parameter itself to its rounded Pass-1 value.
            current = update_one_stellar_parameter(
                current_after_pass2,
                parameter_name,
                float(pass1_rounded),
                use_exact_grid_format=True,
            )
            parameter_errors[parameter_name] = pass1_error
            real_parameter_values[parameter_name] = pass1_real
            LOGGER.warning(
                "PASS-2 INCONSISTENT | iteration %d.2 | %s | Pass-1 rounded=%s | "
                "Pass-2 real=%s | shift=%s > one grid step %.6f | "
                "REVERTING TO PASS-1 value/error (real=%.6f, error=%s)",
                iteration_id,
                parameter_name,
                pass1_rounded_string,
                "nan" if not np.isfinite(pass2_real) else f"{pass2_real:.6f}",
                "nan" if not np.isfinite(consistency_shift) else f"{consistency_shift:.6f}",
                one_grid_step,
                float(pass1_real),
                "nan" if not np.isfinite(pass1_error) else f"{pass1_error:.6f}",
            )

        checkpoint_step(step_name)

    converged = parameter_change_is_converged(starting_parameters, current, config)
    note = (
        "Two-pass sequential GJ205 refinement. Pass 1 uses the original "
        "diagnostic-line strategy; Pass 2 repeats vmic -> [M/H] -> logg -> "
        "Teff over all parameter lines and alpha over alpha-element lines "
        "on five-point local grids restricted to the Pass-1 parameter grids. Pass 2 is accepted only "
        "when its fitted value remains within one original grid step of the "
        "rounded Pass-1 center; otherwise that parameter retains its Pass-1 "
        "value and Pass-1 uncertainty. Each sub-step uses the most recently "
        "updated fixed parameters."
    )

    return ParameterRefinementResult(
        stellar_parameters=current,
        converged=converged,
        note=note,
        parameter_errors=parameter_errors,
        parameter_consistency_shifts=parameter_consistency_shifts,
        real_parameter_values=real_parameter_values,
    )


def run_fixed_atmosphere_abundance_solution(
    label: str,
    stellar_parameters: StellarParameters,
    fixed_final_abundances: np.ndarray,
    species: SpeciesConfig,
    line_lists: List[LineList],
    lam_star: np.ndarray,
    flux_star: np.ndarray,
    err_flux_star: np.ndarray,
    config: AutoSpecFitConfig,
) -> np.ndarray:
    """
    Determine all elemental abundances once at a fixed atmosphere.

    For each target element, all other elemental abundances are held at the
    converged final values while the target abundance alone is varied over the
    standard ASF abundance grid.
    """
    fixed_strings = [
        format_abundance_filename_value(value) if np.isfinite(value) else "+0.000"
        for value in np.asarray(fixed_final_abundances, dtype=float)
    ]

    model_paths = followup_iteration_model_paths(
        config,
        stellar_parameters,
        species,
        fixed_strings,
    )
    commands = followup_iteration_turbospectrum_commands(
        config=config,
        stellar_parameters=stellar_parameters,
        species=species,
        previous_abundance_strings=fixed_strings,
    )

    missing_before_submission = require_models_or_ts_enabled(
        model_paths,
        config.run_turbospectrum,
        f"Systematic abundance run {label}",
    )

    if config.run_turbospectrum:
        if missing_before_submission:
            LOGGER.info(
                "Systematic abundance run %s: %d required model(s) are missing or "
                "empty; submitting Turbospectrum for missing models.",
                label,
                len(missing_before_submission),
            )
        runner = select_turbospectrum_runner(stellar_parameters, config)
        if commands:
            LOGGER.info(
                "Systematic abundance run %s uses TS runner: %s",
                label,
                runner,
            )
            for command in commands:
                run_turbospectrum_command(
                    command=command,
                    runner=runner,
                    execution_prefix=config.turbospectrum_execution_prefix,
                )
        else:
            LOGGER.info(
                "Systematic abundance run %s: all required models already exist.",
                label,
            )

    wait_for_model_files(model_paths, config)

    abundance_grid = np.asarray(config.abundance_values, dtype=float)
    results: List[SpeciesIterationResult] = []
    for species_index in range(species.n_species):
        result = fit_species_in_iteration(
            iteration_id=0,
            species_index=species_index,
            species=species,
            line_list=line_lists[species_index],
            species_model_paths=model_paths[species_index],
            lam_star=lam_star,
            flux_star=flux_star,
            err_flux_star=err_flux_star,
            config=config,
            abundance_grid=abundance_grid,
            log_handle=None,
        )
        results.append(result)

    return np.asarray([result.mean_abundance for result in results], dtype=float)


def parameter_numeric_value(
    stellar_parameters: StellarParameters,
    parameter_name: str,
) -> float:
    """Return one StellarParameters field as a float."""
    attr = {
        "teff": "teff",
        "logg": "logg",
        "metallicity": "metallicity",
        "alpha": "alpha",
        "vmic": "vmic",
    }[parameter_name]
    return float(getattr(stellar_parameters, attr))


def run_systematic_abundance_error_analysis(
    final_stellar_parameters: StellarParameters,
    parameter_errors: Dict[str, float],
    final_abundances: np.ndarray,
    random_abundance_errors: np.ndarray,
    species: SpeciesConfig,
    line_lists: List[LineList],
    lam_star: np.ndarray,
    flux_star: np.ndarray,
    err_flux_star: np.ndarray,
    config: AutoSpecFitConfig,
) -> Tuple[np.ndarray, np.ndarray, Dict[str, np.ndarray]]:
    """
    Propagate final atmospheric-parameter uncertainties into abundances.

    Each fitted parameter is perturbed one at a time by +/-1 sigma. The
    perturbed numerical value is rounded to the nearest value on that
    parameter's actual fitting grid before synthesis. For each element and
    parameter, both the nominal and perturbed ASF offsets are converted to the
    corresponding physical [X/H] scale. Each measured abundance shift is
    linearly rescaled from the actual grid displacement to the requested
    1-sigma displacement. The systematic contribution from one parameter is
    the mean of the available absolute, rescaled +/-1-sigma shifts. Independent
    parameter contributions are then added in quadrature, and the resulting
    systematic error is added in quadrature to the random abundance error.

    This one-at-a-time procedure does not include covariance terms between
    atmospheric parameters.
    """
    # The nominal final atmosphere used for the systematic analysis is itself
    # forced onto the exact adopted grids before any +/-1-sigma perturbation.
    final_stellar_parameters = round_all_stellar_parameters_to_grids(
        config,
        final_stellar_parameters,
    )
    assert_canonical_stellar_parameter_strings(final_stellar_parameters)

    parameter_names = ("vmic", "metallicity", "logg", "teff", "alpha")
    final_abundances = np.asarray(final_abundances, dtype=float)
    random_errors = np.asarray(random_abundance_errors, dtype=float)

    # The native ASF abundances are offsets relative to the final atmosphere.
    # For uncertainty propagation, compare PHYSICAL [X/H] abundances.  This is
    # essential for [M/H] and [alpha/Fe] perturbations because those parameters
    # enter the abundance-scale conversion directly in addition to changing the
    # fitted ASF offset.
    nominal_xh = convert_asf_offsets_to_xh(
        final_abundances, final_stellar_parameters, species, config
    )

    per_parameter: Dict[str, np.ndarray] = {
        name: np.zeros(species.n_species, dtype=float)
        for name in parameter_names
    }
    perturbation_rows: List[Tuple[str, str, float, float, float, str]] = []

    for parameter_name in parameter_names:
        sigma = float(parameter_errors.get(parameter_name, np.nan))
        nominal_value = parameter_numeric_value(
            final_stellar_parameters,
            parameter_name,
        )

        if not np.isfinite(sigma) or sigma <= 0:
            LOGGER.warning(
                "Skipping systematic perturbation for %s because its final "
                "uncertainty is not finite and positive: %s",
                parameter_name,
                sigma,
            )
            per_parameter[parameter_name][:] = np.nan
            perturbation_rows.append(
                (parameter_name, "none", nominal_value, sigma, np.nan, "missing_uncertainty")
            )
            continue

        scaled_shifts: List[np.ndarray] = []
        used_grid_values = set()

        for sign, sign_label in ((+1.0, "plus"), (-1.0, "minus")):
            requested_value = nominal_value + sign * sigma

            # IMPORTANT: for the systematic-error calculation, the nominal
            # parameter is already on its adopted grid. After applying +/-1 sigma,
            # the perturbed value is rounded AGAIN to the nearest point on the
            # same grid before any abundance models are generated.
            # The perturbed value is NEVER sent directly to TS.
            # It is first rounded again to the nearest point on the SAME fitting
            # grid used in the main parameter determination.
            rounded_value, rounded_string = round_parameter_to_nearest_grid(
                config,
                parameter_name,
                requested_value,
            )

            # If sigma is smaller than half a grid step, evaluate the adjacent
            # grid point in the requested direction and linearly scale that
            # response to the reported 1-sigma displacement.
            if np.isclose(rounded_value, nominal_value, atol=1.0e-8, rtol=0.0):
                grid = np.asarray(parameter_grid(config, parameter_name), dtype=float)
                nominal_index = int(np.argmin(np.abs(grid - nominal_value)))
                adjacent_index = nominal_index + (1 if sign > 0 else -1)
                if 0 <= adjacent_index < len(grid):
                    rounded_value = float(grid[adjacent_index])
                    rounded_string = parameter_grid_strings(
                        parameter_name, config
                    )[adjacent_index]

            perturbation_rows.append(
                (
                    parameter_name,
                    sign_label,
                    nominal_value,
                    sigma,
                    rounded_value,
                    rounded_string,
                )
            )

            # At a hard boundary, omit an unavailable side and use the other.
            if (
                not np.isfinite(rounded_value)
                or np.isclose(rounded_value, nominal_value, atol=1.0e-8, rtol=0.0)
                or rounded_string in used_grid_values
            ):
                continue

            used_grid_values.add(rounded_string)
            perturbed_parameters = update_one_stellar_parameter(
                final_stellar_parameters,
                parameter_name,
                rounded_value,
                use_exact_grid_format=True,
            )

            perturbed_abundances = run_fixed_atmosphere_abundance_solution(
                label=f"{parameter_name}_{sign_label}_{rounded_string}",
                stellar_parameters=perturbed_parameters,
                fixed_final_abundances=final_abundances,
                species=species,
                line_lists=line_lists,
                lam_star=lam_star,
                flux_star=flux_star,
                err_flux_star=err_flux_star,
                config=config,
            )

            perturbed_xh = convert_asf_offsets_to_xh(
                perturbed_abundances, perturbed_parameters, species, config
            )
            actual_displacement = abs(float(rounded_value) - nominal_value)
            if not np.isfinite(actual_displacement) or actual_displacement <= 0:
                continue
            scale_to_one_sigma = sigma / actual_displacement
            scaled_shifts.append(
                np.abs(perturbed_xh - nominal_xh) * scale_to_one_sigma
            )

        if scaled_shifts:
            stacked = np.vstack(scaled_shifts)
            finite = np.isfinite(stacked)
            counts = np.sum(finite, axis=0)
            sums = np.nansum(stacked, axis=0)
            averaged = np.full(species.n_species, np.nan, dtype=float)
            available = counts > 0
            averaged[available] = sums[available] / counts[available]
            per_parameter[parameter_name] = averaged
        else:
            # Both +/-1sigma rounded to the nominal parameter grid point.
            per_parameter[parameter_name] = np.zeros(species.n_species, dtype=float)

    # Systematic total: quadrature of finite one-at-a-time contributions.
    systematic_total = np.zeros(species.n_species, dtype=float)
    for species_index in range(species.n_species):
        contributions = np.asarray(
            [
                per_parameter[name][species_index]
                for name in parameter_names
            ],
            dtype=float,
        )
        finite = np.isfinite(contributions)
        if np.any(finite):
            systematic_total[species_index] = float(
                np.sqrt(np.sum(contributions[finite] ** 2))
            )
        else:
            systematic_total[species_index] = np.nan

    total_error = np.full(species.n_species, np.nan, dtype=float)
    valid_total = np.isfinite(random_errors) & np.isfinite(systematic_total)
    total_error[valid_total] = np.sqrt(
        random_errors[valid_total] ** 2
        + systematic_total[valid_total] ** 2
    )

    # The final abundance table is the authoritative uncertainty product.
    # Per-parameter consistency contributions remain available in memory but are
    # not written to separate files.
    return systematic_total, total_error, per_parameter


def perform_parameter_refinement(
    parameter_refiner: ParameterRefiner,
    iteration_id: int,
    stellar_parameters: StellarParameters,
    iteration_results: List[SpeciesIterationResult],
    mean_abundances: np.ndarray,
    rounded_abundances: np.ndarray,
    species: SpeciesConfig,
    line_lists: List[LineList],
    lam_star: np.ndarray,
    flux_star: np.ndarray,
    err_flux_star: np.ndarray,
    config: AutoSpecFitConfig,
) -> ParameterRefinementResult:
    """Run the user-supplied atmospheric-parameter optimizer.

    The callback can implement the preferred scientific strategy (for example,
    sequential [M/H] -> Teff -> log g refinement, or a joint Teff-log g fit).
    It receives the abundances from the just-completed iteration so parameter
    models can be synthesized with the current chemical solution.
    """
    result = parameter_refiner(
        iteration_id=iteration_id,
        stellar_parameters=stellar_parameters,
        iteration_results=iteration_results,
        mean_abundances=np.asarray(mean_abundances, dtype=float).copy(),
        rounded_abundances=np.asarray(rounded_abundances, dtype=float).copy(),
        species=species,
        line_lists=line_lists,
        lam_star=lam_star,
        flux_star=flux_star,
        err_flux_star=err_flux_star,
        config=config,
    )

    if isinstance(result, StellarParameters):
        # Convenience: allow a simple callback to return StellarParameters only.
        result = ParameterRefinementResult(stellar_parameters=result)

    if not isinstance(result, ParameterRefinementResult):
        raise TypeError(
            "parameter_refiner must return ParameterRefinementResult or StellarParameters."
        )

    return result


